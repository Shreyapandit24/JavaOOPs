package org.oopsdata.sppu.home;

public class Tester {
private int testerId;
private String testerName;
private String testerDept;
private float testerSalary;
private Address address;
public int getTesterId() {
	return testerId;
}
public void setTesterId(int testerId) {
	this.testerId = testerId;
}
public String getTesterName() {
	return testerName;
}
public void setTesterName(String testerName) {
	this.testerName = testerName;
}
public String getTesterDept() {
	return testerDept;
}
public void setTesterDept(String testerDept) {
	this.testerDept = testerDept;
}
public float getTesterSalary() {
	return testerSalary;
}
public void setTesterSalary(float testerSalary) {
	this.testerSalary = testerSalary;
}
public Address getAddress() {
	return address;
}
public void setAddress(Address address) {
	this.address = address;
}


}

package org.oopsdata.sppu.home;

public class Developer {
    private int devId;
    private String devName;
    private String devDept;
    private float devSalary;
    private Address address;
	public int getDevId() {
		return devId;
	}
	public void setDevId(int devId) {
		this.devId = devId;
	}
	public String getDevName() {
		return devName;
	}
	public void setDevName(String devName) {
		this.devName = devName;
	}
	public String getDevDept() {
		return devDept;
	}
	public void setDevDept(String devDept) {
		this.devDept = devDept;
	}
	public float getDevSalary() {
		return devSalary;
	}
	public void setDevSalary(float devSalary) {
		this.devSalary = devSalary;
	}
	public Address getAddress() {
		return address;
	}
	public void setAddress(Address address) {
		this.address = address;
	}
    
    
    
}
